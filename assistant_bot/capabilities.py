def capability_prompt_block() -> str:
    supported = "\n".join(f"- {item}" for item in SUPPORTED_CAPABILITIES)
    unsupported = "\n".join(f"- {item}" for item in UNSUPPORTED_CAPABILITIES)
    return (
        "현재 코드로 제공되는 기능:\n"
        f"{supported}\n\n"
        "현재 코드로 제공되지 않는 기능:\n"
        f"{unsupported}"
    )


